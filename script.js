/* =====================================================
   GUARDAR TEXTOS ORIGINAIS
===================================================== */

const originalTextNodes =
    new WeakMap();

const originalAttributes =
    new WeakMap();


function normalizeText(text) {

    return text
        .replace(/\s+/g, " ")
        .trim();
}


/* =====================================================
   TRADUZIR NÓ DE TEXTO
===================================================== */

function translateTextNode(
    node,
    language
) {

    if (
        !node ||
        node.nodeType !== Node.TEXT_NODE
    ) {
        return;
    }


    const parent =
        node.parentElement;


    if (!parent) {
        return;
    }


    if (
        parent.tagName === "SCRIPT" ||
        parent.tagName === "STYLE" ||
        parent.tagName === "NOSCRIPT"
    ) {
        return;
    }


    if (
        !originalTextNodes.has(node)
    ) {

        originalTextNodes.set(
            node,
            node.textContent
        );
    }


    const original =
        originalTextNodes.get(node);


    const cleanOriginal =
        normalizeText(original);


    if (!cleanOriginal) {
        return;
    }


    const dictionary =
        siteTranslations[language];


    if (!dictionary) {
        return;
    }


    const translated =
        dictionary[cleanOriginal];


    if (
        translated === undefined
    ) {
        return;
    }


    const leading =
        original.match(/^\s*/)?.[0] || "";


    const trailing =
        original.match(/\s*$/)?.[0] || "";


    node.textContent =
        leading +
        translated +
        trailing;
}


/* =====================================================
   TRADUZIR ATRIBUTOS
===================================================== */

function translateAttributes(
    element,
    language
) {

    const attributes = [
        "aria-label",
        "title",
        "placeholder",
        "alt"
    ];


    attributes.forEach(
        attribute => {

            if (
                !element.hasAttribute(attribute)
            ) {
                return;
            }


            const originalKey =
                `${attribute}:original`;


            let originals =
                originalAttributes.get(element);


            if (!originals) {

                originals = {};

                originalAttributes.set(
                    element,
                    originals
                );
            }


            if (
                originals[originalKey] === undefined
            ) {

                originals[originalKey] =
                    element.getAttribute(
                        attribute
                    );
            }


            const original =
                originals[originalKey];


            if (!original) {
                return;
            }


            const translated =
                attributeTranslations[
                    original
                ]?.[language];


            if (
                translated
            ) {

                element.setAttribute(
                    attribute,
                    translated
                );
            }

        }
    );
}


/* =====================================================
   TRADUZIR TODA A PÁGINA
===================================================== */

function translateEntireSite(
    language
) {

    const walker =
        document.createTreeWalker(

            document.body,

            NodeFilter.SHOW_TEXT

        );


    const textNodes = [];


    let node;


    while (
        node =
            walker.nextNode()
    ) {

        textNodes.push(node);
    }


    textNodes.forEach(
        textNode => {

            translateTextNode(
                textNode,
                language
            );

        }
    );


    /* ATRIBUTOS */

    document
        .querySelectorAll("*")
        .forEach(
            element => {

                translateAttributes(
                    element,
                    language
                );

            }
        );


    /* TÍTULO DA PÁGINA */

    const titles = {

        pt:
            "Setembro Amarelo | Você Importa",

        en:
            "Yellow September | You Matter",

        es:
            "Septiembre Amarillo | Tú Importas",

        fr:
            "Septembre Jaune | Vous Comptez"

    };


    document.title =
        titles[language] ||
        titles.pt;


    /* HTML LANG */

    const htmlLanguages = {

        pt: "pt-BR",
        en: "en",
        es: "es",
        fr: "fr"

    };


    document.documentElement.lang =
        htmlLanguages[language] ||
        "pt-BR";


    /* BOTÕES DE IDIOMA */

    document
        .querySelectorAll(
            ".language-button"
        )
        .forEach(
            button => {

                const isActive =
                    button.dataset.language ===
                    language;


                button.classList.toggle(
                    "active",
                    isActive
                );


                button.setAttribute(
                    "aria-pressed",
                    isActive
                        ? "true"
                        : "false"
                );

            }
        );


    /* SALVAR IDIOMA */

    localStorage.setItem(
        "siteLanguage",
        language
    );
}


