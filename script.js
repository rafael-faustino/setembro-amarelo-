function setText(selector, text) {
    const element = document.querySelector(selector);

    if (element) {
        element.textContent = text;
    }
}


function setHTML(selector, html) {
    const element = document.querySelector(selector);

    if (element) {
        element.innerHTML = html;
    }
}


