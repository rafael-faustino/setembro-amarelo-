/* =====================================================
   OBSERVADOR
   PEGA TEXTOS CRIADOS DEPOIS PELO JAVASCRIPT
===================================================== */

const translationObserver =
    new MutationObserver(
        mutations => {

            const currentLanguage =
                localStorage.getItem(
                    "siteLanguage"
                ) || "pt";


            mutations.forEach(
                mutation => {

                    if (
                        mutation.type ===
                        "childList"
                    ) {

                        mutation.addedNodes.forEach(
                            addedNode => {

                                if (
                                    addedNode.nodeType ===
                                    Node.TEXT_NODE
                                ) {

                                    translateTextNode(
                                        addedNode,
                                        currentLanguage
                                    );

                                }


                                if (
                                    addedNode.nodeType ===
                                    Node.ELEMENT_NODE
                                ) {

                                    const walker =
                                        document.createTreeWalker(
                                            addedNode,
                                            NodeFilter.SHOW_TEXT
                                        );


                                    const textNodes = [];


                                    let textNode;


                                    while (
                                        textNode =
                                            walker.nextNode()
                                    ) {

                                        textNodes.push(
                                            textNode
                                        );
                                    }


                                    textNodes.forEach(
                                        textNode => {

                                            translateTextNode(
                                                textNode,
                                                currentLanguage
                                            );

                                        }
                                    );


                                    translateAttributes(
                                        addedNode,
                                        currentLanguage
                                    );


                                    addedNode
                                        .querySelectorAll(
                                            "*"
                                        )
                                        .forEach(
                                            element => {

                                                translateAttributes(
                                                    element,
                                                    currentLanguage
                                                );

                                            }
                                        );

                                }

                            }
                        );

                    }

                }
            );

        }
    );


translationObserver.observe(
    document.body,
    {
        childList: true,
        subtree: true
    }
);