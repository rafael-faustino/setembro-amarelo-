    const originalTexts = new WeakMap();
    const originalAttributes = new WeakMap();

    function normalizar(texto) {
        return texto
            .replace(/\s+/g, " ")
            .trim();
    }

    function traduzirTexto(texto, idioma) {
        const tabela = translations[idioma] || translations.pt;
        const textoNormalizado = normalizar(texto);

        if (tabela[textoNormalizado]) {
            return texto.replace(textoNormalizado, tabela[textoNormalizado]);
        }

        return texto;
    }

    function traduzirPagina(idioma) {
        document.documentElement.lang =
            idioma === "pt" ? "pt-BR" :
            idioma === "en" ? "en" :
            idioma === "es" ? "es" : "fr";

        document.querySelectorAll("*").forEach(elemento => {
            if (
                elemento.id === "flowerField" ||
                elemento.id === "butterflies" ||
                elemento.id === "particles" ||
                elemento.classList.contains("sunflower") ||
                elemento.classList.contains("butterfly")
            ) {
                return;
            }

            elemento.childNodes.forEach(node => {
                if (node.nodeType === Node.TEXT_NODE) {
                    const textoOriginal = originalTexts.has(node)
                        ? originalTexts.get(node)
                        : node.nodeValue;

                    if (!originalTexts.has(node)) {
                        originalTexts.set(node, textoOriginal);
                    }

                    node.nodeValue = traduzirTexto(textoOriginal, idioma);
                }
            });

            ["aria-label", "title", "alt"].forEach(atributo => {
                if (elemento.hasAttribute(atributo)) {
                    if (!originalAttributes.has(elemento)) {
                        originalAttributes.set(elemento, {});
                    }

                    const dados = originalAttributes.get(elemento);

                    if (!dados[atributo]) {
                        dados[atributo] = elemento.getAttribute(atributo);
                    }

                    elemento.setAttribute(
                        atributo,
                        traduzirTexto(dados[atributo], idioma)
                    );
                }
            });
        });

        document.title =
            idioma === "pt"
                ? "Setembro Amarelo | Você Importa"
                : idioma === "en"
                ? "Yellow September | You Matter"
                : idioma === "es"
                ? "Septiembre Amarillo | Tú Importas"
                : "Septembre Jaune | Vous Comptez";

        document.querySelectorAll(".language-button").forEach(botao => {
            const ativo = botao.dataset.language === idioma;

            botao.classList.toggle("active", ativo);
            botao.setAttribute("aria-pressed", ativo ? "true" : "false");
        });

        localStorage.setItem("idiomaSite", idioma);
    }

    function configurarIdiomas() {
        document.querySelectorAll(".language-button").forEach(botao => {
            botao.addEventListener("click", () => {
                const idioma = botao.dataset.language;

                if (translations[idioma]) {
                    traduzirPagina(idioma);
                }
            });
        });

        const idiomaSalvo = localStorage.getItem("idiomaSite") || "pt";
        traduzirPagina(idiomaSalvo);
    }

    function observarNovosElementos() {
        const observador = new MutationObserver(() => {
            const idiomaAtual = localStorage.getItem("idiomaSite") || "pt";

            document.querySelectorAll("*").forEach(elemento => {
                elemento.childNodes.forEach(node => {
                    if (node.nodeType === Node.TEXT_NODE) {
                        const original = originalTexts.has(node)
                            ? originalTexts.get(node)
                            : node.nodeValue;

                        if (!originalTexts.has(node)) {
                            originalTexts.set(node, original);
                        }

                        node.nodeValue = traduzirTexto(original, idiomaAtual);
                    }
                });
            });
        });

        observador.observe(document.body, {
            childList: true,
            subtree: true
        });
    }

    if (document.readyState === "loading") {
        document.addEventListener("DOMContentLoaded", () => {
            configurarIdiomas();
            observarNovosElementos();
        });
    } else {
        configurarIdiomas();
        observarNovosElementos();
    }

